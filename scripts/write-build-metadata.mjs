#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const outputPath = path.join(repoRoot, 'lib', 'build-metadata.generated.ts');

function todayUtc() {
  return new Date().toISOString().slice(0, 10);
}

const buildDate = process.env.SITE_BUILD_DATE || todayUtc();
const buildTimestamp = process.env.SITE_BUILD_TIMESTAMP || `${buildDate}T00:00:00Z`;

const content = `// Generated by scripts/write-build-metadata.mjs before build. Do not edit manually.\nexport const SITE_BUILD_DATE = ${JSON.stringify(buildDate)};\nexport const SITE_BUILD_TIMESTAMP = ${JSON.stringify(buildTimestamp)};\n`;

await fs.writeFile(outputPath, content);
console.log(`Wrote ${path.relative(repoRoot, outputPath)} with SITE_BUILD_DATE=${buildDate}`);
